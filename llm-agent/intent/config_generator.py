@dataclass
class IntentPayload:
    """Structured configuration intent generated by the TelcoLLM Agent.

    This payload is serialised to the NetworkIntent protobuf message before
    submission to the DSF via gRPC.

    Attributes:
        intent_id:         Unique identifier for this intent instance.
        rationale:         Human-readable explanation of why this intent was generated.
        generated_at:      ISO-8601 timestamp of intent creation.
        target_element_id: The network element to be reconfigured.
        category:          Intent category (e.g. RADIO_OPTIMIZATION).
        confidence_score:  Confidence of the proposed changes [0.0, 1.0].
        radio_params:      Proposed radio access parameter changes.
        core_params:       Proposed core network parameter changes.
        transport_params:  Proposed transport layer parameter changes.
        security_params:   Proposed security parameter changes.
        reasoning_trace:   Step-by-step trace of the decision process.
        metadata:          Additional context metadata (source anomalies, etc.).
    """

    intent_id: str = ""
    rationale: str = ""
    generated_at: str = ""
    target_element_id: str = ""
    category: str = "RADIO_OPTIMIZATION"
    confidence_score: float = 0.0
    radio_params: dict[str, Any] = field(default_factory=dict)
    core_params: dict[str, Any] = field(default_factory=dict)
    transport_params: dict[str, Any] = field(default_factory=dict)
    security_params: dict[str, Any] = field(default_factory=dict)
    reasoning_trace: list[dict[str, Any]] = field(default_factory=list)
    metadata: dict[str, Any] = field(default_factory=dict)

    def __post_init__(self) -> None:
        if not self.intent_id:
            self.intent_id = f"intent-{uuid.uuid4().hex[:16]}"
        if not self.generated_at:
            self.generated_at = datetime.now(timezone.utc).isoformat()


@dataclass
class ConfigGeneratorConfig:
    """Configuration for the intent generator.

    Attributes:
        element_id_to_type_map: Mapping from element ID prefix to element type
                                 (RAN, CORE, TRANSPORT).
        safety_margins:          Per-parameter safety bounds for constraining
                                 proposed values.
        intent_cooldown_s:       Minimum seconds between intent submissions for
                                 the same element to prevent oscillation.
    """

    element_id_to_type_map: dict[str, str] = field(
        default_factory=lambda: dict(DEFAULT_ELEMENT_TYPE_MAP)
    )
    safety_margins: dict[str, dict[str, float]] = field(
        default_factory=lambda: dict(DEFAULT_SAFETY_MARGINS)
    )
    intent_cooldown_s: float = 5.0


